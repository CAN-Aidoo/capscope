"""results/ -> paper/numbers.tex (macros \\N{key}) and paper/tab_oracle.tex. Every number in the text comes from here."""
import collections
import csv
import json
import os

R = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "results")
P = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "paper")
os.makedirs(P, exist_ok=True)
O = json.load(open(os.path.join(R, "oracle.json")))
T = json.load(open(os.path.join(R, "timing.json")))
rows = list(csv.DictReader(open(os.path.join(R, "oracle_pairs.csv"))))
SUITES = ["workspace", "travel", "banking", "slack"]
N = {}


def pc(x):
    v = 100 * x
    return f"{v:.0f}" if abs(v - round(v)) < 0.05 or v >= 10 else f"{v:.1f}"


def ci(c):
    return f"{pc(c[0])}--{pc(c[1])}"


for m, key in [("MANUAL", "man"), ("AUTO", "auto"), ("ORACLE-CAT", "ocat"), ("ORACLE-TOOL", "otool")]:
    a = O[m]["all"]
    N[f"{key}Pres"] = pc(a["utility_preserved"]); N[f"{key}PresCI"] = ci(a["utility_preserved_ci"])
    N[f"{key}Blk"] = pc(a["blocked"]); N[f"{key}BlkCI"] = ci(a["blocked_ci"])
    N[f"{key}Both"] = pc(a["blocked_and_preserved"]); N[f"{key}BothCI"] = ci(a["blocked_and_preserved_ci"])
    N[f"{key}Denied"] = str(a["benign_calls_denied"])
    for s in SUITES:
        N[f"{key}Blk{s}"] = pc(O[m][s]["blocked"]); N[f"{key}Pres{s}"] = pc(O[m][s]["utility_preserved"])
for m, key in [("MANUAL", "man"), ("AUTO", "auto"), ("ORACLE-TOOL", "otool")]:
    N[f"{key}BlkVone"] = pc(O[m + "_unannotated_only"]["all"]["blocked"])
    N[f"{key}BlkStrict"] = pc(O[m + "_strict_cleanup"]["all"]["blocked"])
a = O["MANUAL"]["all"]
N["nPairs"] = str(a["n_pairs"]); N["nUsers"] = str(a["n_users"]); N["nBenignCalls"] = str(a["benign_calls"])
N["nPairsVone"] = str(O["MANUAL_unannotated_only"]["all"]["n_pairs"])
N["unblockable"] = pc(1 - O["ORACLE-TOOL"]["all"]["blocked"])
N["unblockablebanking"] = pc(1 - O["ORACLE-TOOL"]["banking"]["blocked"])
N["timeMedMs"] = f"{T['median_us'] / 1000:.2f}"
N["timeMaxMs"] = f"{T['max_us'] / 1000:.1f}"

# pair counts behind the gap to the ceiling
by = lambda m: {(r["suite"], r["user"], r["injection"]): r for r in rows if r["manifest"] == m}
man, ocat, otool = by("MANUAL"), by("ORACLE-CAT"), by("ORACLE-TOOL")
gap_cat = sum(1 for k in otool if otool[k]["blocked"] == "1" and man[k]["blocked"] == "0" and ocat[k]["blocked"] == "0")
gap_kw = sum(1 for k in otool if otool[k]["blocked"] == "1" and man[k]["blocked"] == "0" and ocat[k]["blocked"] == "1")
extra = sum(1 for k in otool if otool[k]["blocked"] == "0" and man[k]["blocked"] == "1")
N["gapCat"] = str(gap_cat); N["gapKw"] = str(gap_kw); N["extraBlk"] = str(extra)
N["nUnblk"] = str(sum(1 for k in otool if otool[k]["blocked"] == "0"))
tx = [k for k in otool if otool[k]["blocked"] == "0" and otool[k]["injection_tools"] == ""]
N["nUnblkText"] = str(len(tx))
lost = sorted({(r["suite"], r["user"]) for r in man.values() if r["user_preserved"] == "0"})
N["nLost"] = str(len(lost))
c = collections.Counter(s for s, _ in lost)
for s in SUITES:
    N[f"nLost{s}"] = str(c.get(s, 0))

with open(os.path.join(P, "numbers.tex"), "w") as f:
    f.write("% generated by code/make_numbers.py; do not edit\n")
    for k, v in N.items():
        f.write(f"\\expandafter\\def\\csname n@{k}\\endcsname{{{v}}}\n")
    f.write("\\newcommand{\\N}[1]{\\csname n@#1\\endcsname}\n")

# Table: per suite, utility preserved / blocked for each manifest
names = [("MANUAL", "capscope (hand-written)"), ("AUTO", "capscope (auto keywords)"),
         ("ORACLE-CAT", "oracle categories"), ("ORACLE-TOOL", "oracle tools")]
L = [r"\begin{table}[t]\centering\footnotesize\setlength{\tabcolsep}{2.2pt}",
     r"\caption{Oracle evaluation on AgentDojo v1.2 (%s user tasks, %s user$\times$injection pairs). Each cell: "
     r"user tasks with every ground-truth call allowed (\%%) / pairs in which at least one ground-truth call of the "
     r"injection is denied (\%%). Oracle rows build the manifest from the user task's own ground truth and bound any "
     r"tool-level policy.}\label{tab:oracle}" % (N["nUsers"], N["nPairs"]),
     r"\begin{tabular}{l" + "c" * 5 + "}", r"\toprule",
     r"manifest & workspace & travel & banking & slack & all\\", r"\midrule"]
for m, lab in names:
    cells = [f"{pc(O[m][s]['utility_preserved'])} / {pc(O[m][s]['blocked'])}" for s in SUITES]
    a = O[m]["all"]
    cells.append(f"{pc(a['utility_preserved'])} / {pc(a['blocked'])}")
    L.append(f"{lab} & " + " & ".join(cells) + r"\\")
    if m == "AUTO":
        L.append(r"\midrule")
L += [r"\midrule", r"pairs & %s & %s & %s & %s & %s\\" % tuple(
    [str(O["MANUAL"][s]["n_pairs"]) for s in SUITES] + [N["nPairs"]]), r"\bottomrule", r"\end{tabular}", r"\end{table}"]
open(os.path.join(P, "tab_oracle.tex"), "w").write("\n".join(L) + "\n")
print(len(N), "macros;", N)
